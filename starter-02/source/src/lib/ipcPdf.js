// Quantities can be fractional — show up to 2 dp, trimmed. (Amounts use fmt = rounded SAR, matching the screen.)
const qty = (n) => { const v = Number(n || 0); return v.toLocaleString('en-US', { maximumFractionDigits: 2 }); };

