// ============================================================
// IPC certificate PDF — presentation/output ONLY. Builds a print-ready,
// official-looking Interim Payment Certificate from values the engine ALREADY
// produced and renders it via the browser's print-to-PDF (zero dependency, fully
// client-side, no secrets). The browser's own text engine handles Arabic
// shaping + RTL, so it renders correctly bilingually.
//
// READS ONLY — never recomputes certified value, retention, or VAT:
//   • totals come straight off the IPC record (gross_amount / retention / vat /
//     net_payable) — the exact fields the IPC screen displays.
//   • line rows come from lineReadiness() (the same function the on-screen
//     composition uses) — { contractQty, approvedQty, rate, approvedValue }.
//   • all amounts are formatted with the app's fmt(), so they match the screen
//     character-for-character.
// ============================================================
